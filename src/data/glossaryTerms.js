// 輔助函數：搜尋關鍵字詞條
export const findGlossaryTerm = (keyword) => {
  if (!keyword) return null;
  const clean = keyword.trim();
  for (const [key, val] of Object.entries(GLOSSARY_TERMS)) {
    if (key === clean || clean.includes(key) || key.includes(clean)) {
      return val;
    }
  }
  return null;
};
